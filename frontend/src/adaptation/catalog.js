function cloneQuestion(question) {
    return {
        ...question,
        ...(Array.isArray(question.options) ? { options: [...question.options] } : {}),
        ...(Array.isArray(question.exclusive_options) ? { exclusive_options: [...question.exclusive_options] } : {}),
        ...(Array.isArray(question.special_options)
            ? { special_options: question.special_options.map((option) => ({ ...option })) }
            : {}),
        ...(question.show_if ? { show_if: JSON.parse(JSON.stringify(question.show_if)) } : {}),
    };
}

function cloneQuestions(questions) {
    return (questions || []).map(cloneQuestion);
}

export function formFor(kind, role) {
    if (kind === KIND_CONTROL_2M) return role === ROLE_HR ? cloneQuestions(CONTROL_HR) : [];
    if (role === ROLE_HR) {
        if (kind === KIND_EXTRA) {
            return cloneQuestions([
                q("hr_comment", "Итоговый развернутый комментарий HR.", TEXT, {
                    required: false,
                    hint: "Итоговый вывод, важный контекст, принятые решения и необходимые действия.",
                }),
            ]);
        }
        return cloneQuestions(HR);
    }
    if (role === ROLE_MANAGER) {
        if (kind === KIND_MONTH_1) return cloneQuestions(MANAGER_MONTH);
        if (kind === KIND_MONTH_2) return cloneQuestions(MANAGER_MONTH2);
        return [];
    }
    if (kind === KIND_WEEK_1) return cloneQuestions([...coreEmployee(), ...WEEK_REST]);
    if (kind === KIND_MONTH_1) return cloneQuestions([...coreEmployee(), ...MONTH_REST]);
    if (kind === KIND_MONTH_2) return cloneQuestions([...coreEmployee(), ...MONTH2_REST]);
    if (kind === KIND_EXTRA) return cloneQuestions(EXTRA);
    return cloneQuestions(coreEmployee());
}

/**
 * Keep the approved catalog authoritative even when an older backend returns a
 * stale or accidentally polluted list of options. The server remains the
 * authority for the form composition: normalization never adds omitted
 * questions. Unknown ids are preserved for configurable modules, while known
 * questions get their text, type, conditions and options from the catalog.
 */
export function normalizeQuestionnaire(kind, role, serverQuestions) {
    const approved = formFor(kind, role);
    if (!Array.isArray(serverQuestions)) return approved;
    const incoming = serverQuestions;
    const approvedById = new Map(approved.map((question) => [question.id, question]));
    return incoming
        .filter((question) => question && typeof question.id === "string")
        .map((question) => {
            const canonical = approvedById.get(question.id);
            return canonical
                ? { ...question, ...cloneQuestion(canonical) }
                : cloneQuestion(question);
        });
}

