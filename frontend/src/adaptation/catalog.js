function talk(qid = "talk_hr", stageLabel = "") {
    const suffix = stageLabel ? ` по итогам ${stageLabel}` : "";
    return [
        q(qid, `Хотели бы вы конфиденциально поговорить с HR${suffix}?`, CHOICE, { options: ["да", "нет"] }),
        q(`${qid}_topic`, "Кратко укажите тему разговора, если вам комфортно ее обозначить.", TEXT, {
            required: false,
            show_if: { field: qid, eq: "да" },
        }),
    ];
}

