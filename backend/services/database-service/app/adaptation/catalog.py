def form_for(kind: str, role: str) -> list[dict]:
    if kind == KIND_CONTROL_2M:
        return deepcopy(_CONTROL_HR) if role == ROLE_HR else []
    if role == ROLE_HR:
        if kind == KIND_EXTRA:
            return [
                _q(
                    "hr_comment",
                    "Итоговый развернутый комментарий HR.",
                    TEXT,
                    required=False,
                    hint="Итоговый вывод, важный контекст, принятые решения и необходимые действия.",
                )
            ]
        return deepcopy(_HR)
    if role == ROLE_MANAGER:
        if kind == KIND_MONTH_1:
            return deepcopy(_MANAGER_MONTH)
        if kind == KIND_MONTH_2:
            return deepcopy(_MANAGER_MONTH2)
        return []
    if kind == KIND_WEEK_1:
        return deepcopy([*_core_employee(), *_WEEK_REST])
    if kind == KIND_MONTH_1:
        return deepcopy([*_core_employee(), *_MONTH_REST])
    if kind == KIND_MONTH_2:
        return deepcopy([*_core_employee(), *_MONTH2_REST])
    if kind == KIND_EXTRA:
        return deepcopy(_EXTRA)
    return deepcopy([*_core_employee()])


def form_public_title(kind: str, role: str) -> str:
    if role == ROLE_EMPLOYEE and kind == KIND_EXTRA:
        return "Адаптационный опрос"
    return {
        KIND_WEEK_1: "1 неделя",
        KIND_MONTH_1: "1 месяц",
        KIND_MONTH_2: "2 месяца",
        KIND_CONTROL_2M: "Контроль испытательного периода",
        KIND_EXTRA: "Дополнительная контрольная точка",
    }.get(kind, kind)


def catalog() -> dict:
    kinds = [KIND_WEEK_1, KIND_MONTH_1, KIND_MONTH_2, KIND_CONTROL_2M, KIND_EXTRA]
    roles = [ROLE_EMPLOYEE, ROLE_MANAGER, ROLE_HR]
    return {kind: {role: form_for(kind, role) for role in roles} for kind in kinds}
